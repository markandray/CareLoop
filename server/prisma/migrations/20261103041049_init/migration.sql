    ADD CONSTRAINT "Referral_rejection_reason_check"
    CHECK ("status" <> 'REJECTED' OR "rejectionReason" IS NOT NULL);

ALTER TABLE "Appointment"
    ADD CONSTRAINT "Appointment_delay_reason_check"
    CHECK ("status" NOT IN ('MISSED', 'RESCHEDULED') OR "delayReason" IS NOT NULL);

ALTER TABLE "ContactAttempt"
    ADD CONSTRAINT "ContactAttempt_single_milestone_record_check"
    CHECK (
        NOT ("referralId" IS NOT NULL AND "appointmentId" IS NOT NULL)
        AND ("referralId" IS NULL OR "milestoneState" IN ('REFERRAL_PENDING', 'REFERRAL_ACCEPTED'))
        AND ("appointmentId" IS NULL OR "milestoneState" = 'APPOINTMENT_SCHEDULED')
    );

